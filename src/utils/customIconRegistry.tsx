export const ICON_MAP: Record<string, LucideIcon> = PRESET_ICONS.reduce(
  (acc, curr) => {
    acc[curr.name] = curr.component;
    return acc;
  },
  {} as Record<string, LucideIcon>
);

/**
 * Resolves an icon name against the curated presets first, then the generated
 * tree-shakeable Lucide registry. Shared by the button renderer and the
 * database-driven icon picker so a name behaves identically everywhere.
 */
export function resolveIconComponent(iconName?: string): LucideIcon | undefined {
  if (!iconName) return undefined;
  const raw = iconName.trim();
  if (!raw || raw.toLowerCase() === "none") return undefined;
  const direct = ICON_MAP[raw] || ICON_MAP[raw.toLowerCase()] || ICON_MAP[raw.toUpperCase()];
  if (direct) return direct;
  const normalised = raw
    .replace(/^lucide[-:]/i, "")
    .replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
    .replace(/^(.)/, (c) => c.toUpperCase());
  const withoutIconSuffix = normalised.endsWith("Icon") ? normalised.slice(0, -4) : "";
  return (
    ICON_MAP[normalised] ||
    LUCIDE_ICON_MAP[normalised] ||
    (withoutIconSuffix ? ICON_MAP[withoutIconSuffix] || LUCIDE_ICON_MAP[withoutIconSuffix] : undefined)
  );
}

/**
 * Renders an icon based on button customization config or defaults
 */
export function renderCustomIcon(
  config: ButtonCustomConfig | undefined,
  defaultIconComponent: React.ReactNode,
  className: string = "w-4 h-4"
): React.ReactNode {
  if (!config) return defaultIconComponent;

  // 1. Custom uploaded image (Data URI or URL)
  if (config.customIconType === "image" && config.customIconData) {
    return (
      <img
        src={config.customIconData}
        alt={config.label || "custom icon"}
        className={`${className} object-contain rounded-xs shrink-0 select-none`}
        referrerPolicy="no-referrer"
      />
    );
  }

  // 2. Custom SVG markup
  if (config.customIconType === "svg" && config.customIconData) {
    try {
      return (
        <span
          className={`${className} inline-flex items-center justify-center shrink-0 fill-current svg-custom-icon`}
          dangerouslySetInnerHTML={{ __html: config.customIconData }}
        />
      );
    } catch (e) {
      console.error("Failed to render custom SVG icon", e);
    }
  }

  // 3. Custom Emoji
  if (config.customIconType === "emoji" && config.customIconData) {
    return (
      <span className="text-sm leading-none shrink-0 inline-flex items-center justify-center select-none">
        {config.customIconData}
      </span>
    );
  }

  // 4. Preset icon from the Lucide registry (curated + generated)
  const LucideComp = resolveIconComponent(config.iconName);
  if (LucideComp) {
    return <LucideComp className={className} />;
  }

  // Fallback to default React component passed in
  return defaultIconComponent;
}
